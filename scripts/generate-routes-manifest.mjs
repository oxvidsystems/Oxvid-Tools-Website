// Generates middleware-routes.generated.js: a flat list of every valid
// client-side route, derived from the same tool/category data as
// sitemap.xml. middleware.js imports this to (a) return a genuine HTTP 404
// for any path that isn't a real route instead of the SPA rewrite's soft
// 200, and (b) know which paths it may serve a prerendered snapshot for.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const engineSrc = readFileSync(path.join(__dirname, '../src/core/engine-core.js'), 'utf8');

function extractArrayLiteral(varName) {
  const start = engineSrc.indexOf(`const ${varName} = [`);
  if (start === -1) throw new Error(`generate-routes-manifest: could not find ${varName}`);
  const bracketStart = engineSrc.indexOf('[', start);
  const closeMarker = engineSrc.indexOf('\n];', bracketStart);
  const literal = engineSrc.slice(bracketStart, closeMarker + 2);
  // eslint-disable-next-line no-new-func
  return new Function(`return ${literal}`)();
}

const RAW_TOOLS = extractArrayLiteral('RAW_TOOLS');
const CATEGORIES = extractArrayLiteral('CATEGORIES');

const STATIC_ROUTES = ['/', '/tools', '/categories', '/about', '/contact', '/privacy', '/terms'];
const categoryRoutes = CATEGORIES.map((c) => `/category/${c.key}`);
const toolRoutes = RAW_TOOLS.map(([id]) => `/tool/${id}`);

const allRoutes = [...STATIC_ROUTES, ...categoryRoutes, ...toolRoutes];

const out = `// Auto-generated by scripts/generate-routes-manifest.mjs — do not edit by
// hand. Re-run it (or \`npm run build\`, which runs it automatically)
// whenever tools or categories change.
export const VALID_ROUTES = ${JSON.stringify(allRoutes, null, 2)};
`;

writeFileSync(path.join(__dirname, '../middleware-routes.generated.js'), out);
console.log(`generate-routes-manifest: wrote ${allRoutes.length} routes to middleware-routes.generated.js`);
